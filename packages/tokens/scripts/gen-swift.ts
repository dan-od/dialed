// Generates Swift colour tokens for the widget/Live Activity target from tokens.json (never hand-copied).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const here = dirname(new URL(import.meta.url).pathname);
const tokens = JSON.parse(readFileSync(resolve(here, '../src/tokens.json'), 'utf8'));
const out = resolve(process.argv[2] ?? resolve(here, '../dist/Theme.swift'));

function swiftColor(v: string): string {
  const hex = /^#([0-9A-Fa-f]{6})$/.exec(v);
  if (hex) {
    const n = parseInt(hex[1]!, 16);
    return `Color(red: ${((n >> 16) & 255) / 255}, green: ${((n >> 8) & 255) / 255}, blue: ${(n & 255) / 255})`;
  }
  const rgba = /^rgba\((\d+),(\d+),(\d+),([.\d]+)\)$/.exec(v.replace(/\s/g, ''));
  if (!rgba) throw new Error(`Unsupported colour ${v}`);
  return `Color(red: ${Number(rgba[1]) / 255}, green: ${Number(rgba[2]) / 255}, blue: ${Number(rgba[3]) / 255}, opacity: ${rgba[4]})`;
}

let s =
  '// GENERATED by packages/tokens/scripts/gen-swift.ts — do not edit.\nimport SwiftUI\n\nenum DialedTheme {\n';
for (const theme of ['dark', 'light']) {
  s += `  enum ${theme === 'dark' ? 'Dark' : 'Light'} {\n`;
  for (const [k, v] of Object.entries(tokens.color[theme] as Record<string, string>))
    s += `    static let ${k} = ${swiftColor(v)}\n`;
  s += '  }\n';
}
s += '}\n';
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, s);
console.log(`wrote ${out}`);
